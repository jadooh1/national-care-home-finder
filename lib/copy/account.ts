export const copy: Record<Locale, typeof en> = { en, es };

export function localizedAuthServerMessage(locale: Locale, message: string): string {
  if (locale !== "es") return message;
  if (message === copy.en.owner.invalidCredentials) return copy.es.owner.invalidCredentials;
  if (message === copy.en.owner.emailNotConfirmed) return copy.es.owner.emailNotConfirmed;
  return message;
}
